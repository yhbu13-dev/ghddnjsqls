function main() {
  const file = process.env.DB_FILE || path.join(process.env.DATA_DIR || path.join(__dirname, '../data'), 'order.db');
  const db = open(file);
  if (db.get('SELECT COUNT(*) AS n FROM items').n > 0) {
    console.log('이미 품목이 있어 건너뜁니다.');
    return;
  }
  db.tx(() => {
    let sort = 0;
    const put = (cat, groups, fn) => {
      for (const [grp, list] of Object.entries(groups)) {
        for (const row of list) {
          const [name, price, spec, unit] = fn(row);
          db.run('INSERT INTO items (category, grp, name, spec, unit, price, sort) VALUES (?, ?, ?, ?, ?, ?, ?)', [cat, grp, name, spec, unit, price, sort += 10]);
        }
      }
    };
    put('snack', SNACK, ([n, p]) => [n, p, '', '개']);
    put('cafe', CAFE, ([n, p, s, u]) => [n, p, s, u]);
    put('beverage', BEV, ([n, p]) => [n, p, '1박스', '박스']);
  });
  const stores = [
    { name: '해오름사우나', biz: 'sauna', owner: '김사장' },
    { name: '카페 온도', biz: 'cafe', owner: '이사장' },
    { name: '할매국밥 본점', biz: 'restaurant', owner: '박사장' },
  ];
  for (const s of stores) {
    const r = O.createStore(db, s);
    console.log(`${s.name} (${O.BIZ[s.biz].label}) 연결 코드: ${r.code}`);
  }
  console.log(`품목 ${db.get('SELECT COUNT(*) AS n FROM items').n}개를 넣었습니다.`);
}

main();
